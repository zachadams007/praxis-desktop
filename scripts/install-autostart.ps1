# install-autostart.ps1 - robust autostart for the global hotkey that SURVIVES a shutdown.
#
# Why this shape (after a Scheduled Task proved unverifiable - it ran GUI launches in a
# context where `start` failed, LastTaskResult=1, and I can't test it without a real login):
#   • HKCU Run key - the mechanism that DID reliably launch Praxis at login before; the failures
#     were never "it didn't launch", they were a corrupt WebView2 cache + a bad build.
#   • A SILENT VBScript launcher (wscript, window style 0 = no console flash) that CLEARS the
#     WebView2 cache first. That cache corrupts on a hard shutdown - it blanks the window AND can
#     stop setup() (so the hotkey never registers). Clearing it every login can't leave a dead key.
#   • The app no longer self-registers autostart (removed in lib.rs), so nothing overwrites this.
# Verifiable NOW: run the .vbs → Praxis launches + registers the hotkey (see praxis-boot.log).
#
# Idempotent. Run:  powershell -ExecutionPolicy Bypass -File scripts\install-autostart.ps1
$ErrorActionPreference = 'Stop'

$installDir = Join-Path $env:LOCALAPPDATA 'Praxis'
$exe        = Join-Path $installDir 'praxis.exe'
$vbs        = Join-Path $installDir 'launch-praxis.vbs'
New-Item -ItemType Directory -Force -Path $installDir | Out-Null

# 1) silent launcher: clear the (possibly shutdown-corrupted) WebView2 cache, then start hidden
# NOTE (2026-07-05): the launcher no longer wipes EBWebView. That rmdir deleted the whole
# WebView2 data folder INCLUDING Local Storage - tasks, trust level, fleet/brain picks and
# galaxy tuning were silently reset at every login. The app now self-heals the corruptible
# cache dirs itself on every start (lib.rs clear_webview_caches - caches only, storage kept).
@"
' Praxis autostart launcher (generated by scripts/install-autostart.ps1) - runs silently via wscript.
Set sh = CreateObject("WScript.Shell")
sh.Run """$exe"" --hidden", 0, False
"@ | Set-Content -Path $vbs -Encoding ASCII
Write-Output "wrote launcher: $vbs"

# 2) clean up the prior (broken) Scheduled Task if it exists
Unregister-ScheduledTask -TaskName 'Praxis' -Confirm:$false -ErrorAction SilentlyContinue

# 3) the Run key → the silent launcher (wscript runs the .vbs with no window)
$runCmd = "wscript.exe `"$vbs`""
Set-ItemProperty 'HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Run' -Name Praxis -Value $runCmd
Write-Output "set HKCU Run\Praxis = $runCmd"
Write-Output "DONE."
